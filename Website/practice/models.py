"""Progress storage for the practice tools (scope: [[Music Interval Learning App]] §4).

Decisions worth knowing before changing anything here:

* **One row per answered question, NOT an aggregate counter.** Scoping considered
  a per-user JSON blob — it matched the source artifact exactly — and rejected it.
  A blob is a payload the client controls entirely, so it needs both shape *and*
  size validation against unbounded JSON, and a replayed payload can silently
  corrupt a stored total with no way to audit it afterwards. A fixed-size row
  needs three field checks and has no size vector at all.

* **``client_id`` is what makes a retried save safe.** The browser batches
  attempts and POSTs them; if the response is lost, the batch is re-sent. The
  unique constraint on ``(user, client_id)`` absorbs the duplicate, so nothing is
  ever counted twice. This replaces the idempotency problem the artifact had,
  where additive ``{correct, total}`` counters silently doubled if merged twice.

* **Progress is stored ONLY for a signed-in user** (scope §2.5). There is no
  anonymous persistence, and therefore no local-to-server merge, no history
  deduplication and no merge marker. The server is the only place progress lives.
  ⚠️ Anonymous visitors still *see* in-session statistics — the tool computes
  those in memory. What is gated is persistence, not display.

* **``tool`` is a slug, not a foreign key.** A second drill should not need a
  migration or a lookup-table row to exist; it writes a different slug.

* **Statistics are aggregate queries over this table**, never a stored summary.
  A cached summary that drifts from its source is the failure this project keeps
  meeting; there is nothing to drift if nothing is cached.
"""

from django.conf import settings
from django.core.validators import MaxValueValidator, MinValueValidator
from django.db import models

# Module level, not class level: a nested ``Meta`` cannot see names defined in
# the enclosing class body, so the CheckConstraint below needs them out here.
# The class re-exports both so callers can say PracticeAttempt.MIN_STEPS.
MIN_STEPS = -7
MAX_STEPS = 7
DEFAULT_TOOL = "interval-ladder"


class PracticeAttempt(models.Model):
    """A single answered question. One row per answer, append-only."""

    # The scale spans eight degrees, so a signed interval runs from a descending
    # octave to an ascending one. Enforced by validators (forms/admin) AND by a
    # database CheckConstraint, because the API writes with bulk_create, which
    # does not call full_clean().
    MIN_STEPS = MIN_STEPS
    MAX_STEPS = MAX_STEPS

    DEFAULT_TOOL = DEFAULT_TOOL

    class Mode(models.TextChoices):
        NOTES = "notes", "Hear the note"
        INTERVALS = "intervals", "Name the interval"
        SING = "sing", "Sing it"

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="practice_attempts",
    )
    tool = models.SlugField(max_length=64, default=DEFAULT_TOOL)
    mode = models.CharField(max_length=16, choices=Mode.choices)
    interval_steps = models.SmallIntegerField(
        validators=[MinValueValidator(MIN_STEPS), MaxValueValidator(MAX_STEPS)],
        help_text="Signed scale steps: -7 (octave down) to 7 (octave up); 0 is a unison.",
    )
    correct = models.BooleanField()
    # Generated by the browser so a re-sent batch is harmless. Not a secret and
    # not trusted for anything beyond deduplication within one user's own rows.
    client_id = models.UUIDField()
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at", "-id"]
        constraints = [
            # Scoped to the user on purpose: two people's clients may generate
            # the same id without colliding, and a global unique index would
            # leak one user's write into another's failure.
            models.UniqueConstraint(
                fields=["user", "client_id"],
                name="practice_attempt_unique_client_id_per_user",
            ),
            models.CheckConstraint(
                condition=models.Q(interval_steps__gte=MIN_STEPS, interval_steps__lte=MAX_STEPS),
                name="practice_attempt_interval_steps_in_range",
            ),
        ]
        indexes = [
            # Serves the aggregate the progress view runs: count and sum of
            # `correct`, grouped by interval, for one user and tool.
            models.Index(
                fields=["user", "tool", "mode", "interval_steps"],
                name="practice_attempt_stats_idx",
            ),
        ]

    def __str__(self):
        direction = "unison" if self.interval_steps == 0 else f"{self.interval_steps:+d}"
        return f"{self.user} {self.mode} {direction} {'ok' if self.correct else 'miss'}"
